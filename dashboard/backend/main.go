// version is set at build time (-X main.version, the Makefile and
// dashboard/Dockerfile).
var version = "dev"

func main() {
	if len(os.Args) > 1 && os.Args[1] == "reset-user" {
		resetUser(os.Args[2:])
		return
	}
	if len(os.Args) > 1 && os.Args[1] == "restore" {
		restoreCommand(os.Args[2:])
		return
	}
	addr := flag.String("addr", envOr("JANUS_CONTROLLER_ADDR", ":8080"), "main HTTPS address (node list, add/remove - never a credential) - e.g. \":443\" to run the UI on the standard HTTPS port; also settable via JANUS_CONTROLLER_ADDR (same \":port\"/\"host:port\" format - a flag takes precedence over the env var if both are given), for Docker Compose deployments where an environment: entry is more natural than overriding the container's command")
	registerAddr := flag.String("register-addr", ":8443", "TLS address nodes self-register against (see internal/pending) - not the same port pool as approved nodes' own per-node listeners")
	dataDir := flag.String("data-dir", "/data", "persistent data directory (Docker volume) - node registry + this dashboard's own TLS identity")
	advertiseAddresses := flag.String("advertise-address", envOr("JANUS_CONTROLLER_ADVERTISE_ADDRESS", ""), "comma-separated extra IPs/hostnames to add to this dashboard's TLS identity certificate, alongside loopback and this host's own local IPs (see internal/identity) - needed whenever a node or browser reaches -addr/-register-addr through an address this process can't see on its own network interfaces (Docker bridge networking's host-side published port, a NAT/port-forwarded address, ...); an address added here gets a new certificate at the next start, signed by the same identity CA (the -addr port serves -tls-cert/-tls-key instead when they're set); also settable via JANUS_CONTROLLER_ADVERTISE_ADDRESS, same reasoning as JANUS_CONTROLLER_ADDR above")
	tlsCertFile := flag.String("tls-cert", envOr("JANUS_CONTROLLER_TLS_CERT", ""), "path to a PEM certificate (then its chain) the main HTTPS port (-addr) serves - the page, janusctl, Terraform - instead of the Controller's self-signed identity, read again when the file changes (a renewal needs no restart); with -tls-key, both or neither; nodes keep registering against the self-signed identity on -register-addr; also settable via JANUS_CONTROLLER_TLS_CERT; without it, an admin can upload one on the page")
	masterKeyFile := flag.String("master-key-file", envOr("JANUS_CONTROLLER_MASTER_KEY_FILE", ""), "the master key sealing the fleet's issuing CA key (internal/secrets), made there the first time - keep it outside -data-dir so a copy of the data holds nothing usable; empty: <data-dir>/master.key, which the Controller warns about; also settable via JANUS_CONTROLLER_MASTER_KEY_FILE")
	tlsKeyFile := flag.String("tls-key", envOr("JANUS_CONTROLLER_TLS_KEY", ""), "path to the PEM private key matching -tls-cert; also settable via JANUS_CONTROLLER_TLS_KEY")
	acmeClient := flag.String("acme-client", envOr("JANUS_CONTROLLER_ACME_CLIENT", ""), "the ACME client the Controller orders its nodes' certificates with (cmd/janus-acme, docs/guide/letsencrypt-controller.md) - default: janus-acme next to dashboardd, as in the image; also settable via JANUS_CONTROLLER_ACME_CLIENT")
	imageFactory := flag.String("image-factory", envOr("JANUS_CONTROLLER_IMAGE_FACTORY", nodeproxy.ImageFactoryURL), "image factory that builds and serves the updates of nodes whose image has optional extensions (docs/image-factory.md) - empty to disable, in which case such nodes have no update source; nodes with the default schematic update from GitHub Releases either way; also settable via JANUS_CONTROLLER_IMAGE_FACTORY")
	imageFactoryMirror := flag.String("image-factory-mirror", envOr("JANUS_CONTROLLER_IMAGE_FACTORY_MIRROR", "auto"), "where nodes with optional extensions get their updates when the image factory can't be reached (no connection, no answer within 10 s, a 5xx): a read-only copy of the update bundles it built for its two newest releases (docs/image-factory.md) - \"auto\": "+nodeproxy.DefaultImageFactoryMirror+" with the default -image-factory, none with another; empty: none; also settable via JANUS_CONTROLLER_IMAGE_FACTORY_MIRROR")
	updaterSocket := flag.String("updater-socket", envOr("JANUS_CONTROLLER_UPDATER_SOCKET", updaterapi.DefaultSocket), "Unix socket of janus-controller-updater, which updates this Controller when asked from its page (dashboard/README.md, Updating the Controller) - nothing happens when it isn't there; empty to never use one; also settable via JANUS_CONTROLLER_UPDATER_SOCKET")
	telemetryMode := flag.String("telemetry", envOr("JANUS_CONTROLLER_TELEMETRY", ""), "\"off\": the daily usage report (docs/guide/telemetry.md) stays off, and the page can't turn it on; empty: an admin decides, at setup or on the Settings page (off until then); also settable via JANUS_CONTROLLER_TELEMETRY")
	telemetryURL := flag.String("telemetry-url", envOr("JANUS_CONTROLLER_TELEMETRY_URL", telemetry.DefaultURL), "where the usage report goes, when an admin turned it on; also settable via JANUS_CONTROLLER_TELEMETRY_URL")
	releasesURL := flag.String("releases-url", envOr("JANUS_CONTROLLER_RELEASES_URL", nodeproxy.ReleasesURL), "GitHub API URL listing Janus releases, newest first - where the Controller learns about new releases for itself and its nodes (a mirror, or a test's fake); also settable via JANUS_CONTROLLER_RELEASES_URL")
	flag.Parse()
	nodeproxy.ImageFactoryURL = *imageFactory
	nodeproxy.ImageFactoryMirrorURL = nodeproxy.MirrorFor(*imageFactory, *imageFactoryMirror)
	nodeproxy.ReleasesURL = *releasesURL
	nodeproxy.ControllerVersion = version

	if err := dataWritable(*dataDir); err != nil {
		log.Fatal(err)
	}
	if err := keyReadable(*masterKeyFile); err != nil {
		log.Fatal(err)
	}
	st, err := store.Open(*dataDir)
	if err != nil {
		log.Fatalf("open store: %v", err)
	}

	pendingStore, err := pending.Open(*dataDir)
	if err != nil {
		log.Fatalf("open pending store: %v", err)
	}

	authStore, err := auth.Open(*dataDir)
	if err != nil {
		log.Fatalf("open auth store: %v", err)
	}
	tokenStore, err := auth.OpenTokens(*dataDir)
	if err != nil {
		log.Fatalf("open API token store: %v", err)
	}
	if authStore.SetupRequired() {
		log.Printf("no account yet - the UI will force a one-time setup screen on first visit")
	}
	auditLog, err := audit.Open(*dataDir)
	if err != nil {
		log.Fatalf("open the audit: %v", err)
	}

	controllerID, err := loadOrCreateControllerID(*dataDir)
	if err != nil {
		log.Fatalf("controller ID: %v", err)
	}
	hypervisorStore, err := hypervisor.Open(*dataDir)
	if err != nil {
		log.Fatalf("open hypervisor store: %v", err)
	}
	enrollStore, err := enroll.Open(*dataDir)
	if err != nil {
		log.Fatalf("open the enrollment tokens: %v", err)
	}
	machineStore, err := machines.Open(*dataDir)
	if err != nil {
		log.Fatalf("open machine store: %v", err)
	}
	masterKey, err := secrets.LoadOrCreate(*masterKeyFile, *dataDir)
	if err != nil {
		log.Fatalf("master key: %v", err)
	}
	if masterKey.BesideData {
		log.Printf("WARNING: the master key is %s, in the data directory: a copy of it holds the fleet's issuing CA key, the identity CA's and the accounts' authenticator secrets - set JANUS_CONTROLLER_MASTER_KEY_FILE to a file outside it (dashboard/README.md)", masterKey.Path)
	}
	controllerIdentity, err := identity.Open(*dataDir, masterKey, *advertiseAddresses)
	if err != nil {
		log.Fatalf("the Controller's TLS identity: %v", err)
	}
	authStore.SetSealer(masterKey)
	uiCert, err := uitls.Open(*dataDir, masterKey, controllerIdentity.Certificate, *tlsCertFile, *tlsKeyFile)
	if err != nil {
		log.Fatalf("HTTPS certificate: %v", err)
	}
	backupStore, err := backup.OpenStore(filepath.Join(*dataDir, "backup"), masterKey, controllerID)
	if err != nil {
		log.Fatalf("open the backups: %v", err)
	}
	fleetStore, err := fleet.Open(filepath.Join(*dataDir, "fleet"), masterKey, controllerID)
	if err != nil {
		log.Fatalf("open the fleet: %v", err)
	}
	ssoStore, err := sso.Open(*dataDir, masterKey)
	if err != nil {
		log.Fatalf("open the single sign-on settings: %v", err)
	}
	if *telemetryMode != "" && *telemetryMode != "off" {
		log.Fatalf("-telemetry: %q is neither \"off\" nor empty", *telemetryMode)
	}
	telemetryStore, err := telemetry.Open(*dataDir, *telemetryMode == "off")
	if err != nil {
		log.Fatalf("open the telemetry settings: %v", err)
	}
	clusterStore, err := clusters.Open(*dataDir, masterKey)
	if err != nil {
		log.Fatalf("open the clusters: %v", err)
	}
	nodeproxy.FleetIdentity = func(n *store.Node) (*tls.Certificate, error) { return fleetStore.ClientCertificateFor(n.Bundle()) }
	nodeproxy.NodeCA = func(n *store.Node, caPEM []byte) error { return st.SetCA(n.ID, caPEM) }

	app := &app{
		store:                 st,
		pending:               pendingStore,
		auth:                  authStore,
		tokens:                tokenStore,
		loginLimiter:          auth.NewLoginLimiter(),
		registerLimiter:       ratelimit.New(registerBurst, registerEvery),
		audit:                 auditLog,
		backups:               backupStore,
		masterKeyPath:         masterKey.Path,
		identity:              controllerIdentity,
		ui:                    uiCert,
		suggestedRegisterAddr: suggestRegisterAddress(*advertiseAddresses, *registerAddr),
		selfUpdate:            newSelfUpdate(*updaterSocket),
		dataDir:               *dataDir,
		controllerID:          controllerID,
		hypervisors:           hypervisorStore,
		machines:              machineStore,
		enroll:                enrollStore,
		fleet:                 fleetStore,
		trust:                 newTrustTracker(),
		sso:                   newSingleSignOn(ssoStore),
		telemetry:             telemetryStore,
		telemetryURL:          *telemetryURL,
	}
	app.runner = newMachineRunner(app)
	app.clusters = newClusterEngine(app, clusterStore)
	app.nodeMetrics = newNodeMetrics(app)
	if err := app.startRegistrationListener(*registerAddr); err != nil {
		log.Fatalf("registration listener: %v", err)
	}
	app.runner.resume()
	go app.runner.syncLoop(context.Background())
	app.autoscaler = newAutoscaler(app)
	go app.autoscaler.run(context.Background())
	app.clusterScaler = newClusterScaler(app)
	go app.clusterScaler.run(context.Background())
	go app.trustLoop(context.Background())
	go app.clusters.loop(context.Background())
	go app.backupLoop(context.Background())
	go app.identityLoop(context.Background())
	go app.telemetryLoop(context.Background())
	if err := app.startLogForwarding(masterKey); err != nil {
		log.Fatalf("log forwarding: %v", err)
	}
	app.startACMERelay()
	if err := app.startACMEOrdering(masterKey, *acmeClient); err != nil {
		log.Fatalf("lets encrypt ordering: %v", err)
	}
	if err := app.startConsul(masterKey); err != nil {
		log.Fatalf("consul: %v", err)
	}
	// The node pages: a machine's lock, and its record read again after a
	// change made there.
	nodeproxy.LockedBy = func(n *store.Node) string {
		if m, ok := app.machines.Get(n.MachineID); ok && n.MachineID != "" && m.Spec.Locked {
			return or(m.Spec.ManagedBy, "code")
		}
		return ""
	}
	nodeproxy.NodeChanged = app.runner.syncNode
	// A member's page: its roles on its cluster's router, when the
	// cluster's RouterOS hook reads it.
	nodeproxy.ClusterRouter = app.memberRouterView

	spaFiles, err := fs.Sub(staticFiles, "static")
	if err != nil {
		log.Fatalf("static assets: %v", err)
	}
	// The page's files with an ETag, gzip and Cache-Control
	// (internal/webstatic): http.FileServerFS sent none of them for
	// embedded files, so every page load fetched the whole 560 KB again.
	spa, err := webstatic.SPA(spaFiles)
	if err != nil {
		log.Fatalf("static assets: %v", err)
	}

	srv := &http.Server{
		Addr: *addr,
		// The session cookie's SameSite=Strict already keeps it off
		// cross-site requests, but not off same-site ones (another port
		// or subdomain of the same host) - refuse any non-safe request
		// from another origin outright, the same protection every
		// per-node listener has (see nodeproxy.newHandler).
		Handler: securityHeaders(app.unlessRestored(http.NewCrossOriginProtection().Handler(app.audited(app.routes(spa))))),
		// A connection has 10 s to say what it wants and 2 min of
		// silence before it's closed; no WriteTimeout: the event
		// streams (SSE), the consoles and the packet captures last as
		// long as the page keeps them.
		ReadHeaderTimeout: 10 * time.Second,
		IdleTimeout:       2 * time.Minute,
		MaxHeaderBytes:    64 << 10,
		TLSConfig:         &tls.Config{GetCertificate: uiCert.GetCertificate, MinVersion: tls.VersionTLS12},
	}
	ln, err := net.Listen("tcp", *addr)
	if err != nil {
		log.Fatalf("listen on %s: %v", *addr, err)
	}
	log.Printf("dashboardd %s listening on %s (HTTPS only)", version, *addr)
	// Listening now: an update waiting for this version to start can stop
	// waiting.
	go app.selfUpdate.announce()
	// Empty cert/key file arguments: srv.TLSConfig.GetCertificate above
	// is what's actually used - ServeTLS falls back to it exactly for
	// this case (see its own doc comment).
	log.Fatal(srv.ServeTLS(ln, "", ""))
}

// routes is the main port's API and the page: every API route behind a
// gate naming the role a read and a change of it need.
func (a *app) routes(spa http.Handler) *http.ServeMux {
	nodeAssets, err := nodeproxy.Static()
	if err != nil {
		panic(err) // embedded: a bug, caught at start
	}
	mux := http.NewServeMux()
	mux.HandleFunc("/api/auth/status", a.handleAuthStatus)
	mux.HandleFunc("POST /api/auth/setup", a.handleAuthSetup)
	mux.HandleFunc("POST /api/auth/login", a.handleAuthLogin)
	mux.HandleFunc("POST /api/auth/logout", a.handleAuthLogout)
	mux.HandleFunc("POST /api/auth/password", a.handleAuthPassword)
	a.registerMFARoutes(mux)
	a.registerPreferenceRoutes(mux)
	a.registerTrustRoutes(mux)
	a.registerSSORoutes(mux)
	// The nodes an account reaches - its role over everything, or its
	// grants' labels (access.go); adding, removing and labelling them is
	// an admin's.
	mux.HandleFunc("/api/nodes", a.gate(anyone, auth.Admin, a.handleNodes))
	mux.HandleFunc("GET /api/nodes/status", a.gate(anyone, anyone, a.handleNodesStatus))
	mux.HandleFunc("GET /api/nodes/metrics", a.gate(anyone, anyone, a.handleNodesMetrics))
	mux.HandleFunc("GET /api/version", a.gate(anyone, anyone, func(w http.ResponseWriter, _ *http.Request) {
		writeJSON(w, http.StatusOK, map[string]string{"version": version})
	}))
	mux.HandleFunc("/api/nodes/", a.gate(auth.Reader, auth.Admin, a.handleNode))
	mux.HandleFunc("/api/pending", a.gate(anyone, auth.Admin, a.handlePendingList)) // none for an account without a role over everything
	mux.HandleFunc("/api/pending/", a.gate(auth.Reader, auth.Admin, a.handlePendingAction))
	mux.HandleFunc("/api/controller-info", a.gate(auth.Reader, auth.Admin, a.handleControllerInfo))
	mux.HandleFunc("/api/controller/update", a.gate(auth.Reader, auth.Admin, a.handleControllerUpdate))
	a.registerControllerTLSRoutes(mux)
	mux.HandleFunc("/nodes/", a.handleNodePage)
	// The node pages' hashed assets, the same for every node: one path,
	// cached once (nodeproxy.Static); public like the pages themselves.
	mux.Handle("/node-app/", http.StripPrefix("/node-app", nodeAssets))
	a.registerTokenRoutes(mux)
	a.registerEnrollRoutes(mux)
	a.registerUserRoutes(mux)
	a.registerCLIRoutes(mux)
	a.registerSSHKeyRoutes(mux)
	a.registerCLIBrowserRoutes(mux)
	a.registerBackupRoutes(mux)
	a.registerTelemetryRoutes(mux)
	a.registerLogForwardingRoutes(mux)
	a.registerACMERelayRoutes(mux)
	a.registerACMEOrderingRoutes(mux)
	a.registerConsulRoutes(mux)
	a.registerRestoreRoutes(mux)
	a.registerHypervisorRoutes(mux)
	a.registerFleetRoutes(mux)
	a.registerMachineRoutes(mux)
	a.registerClusterRoutes(mux)
	mux.Handle("/", spa)
	return mux
}

